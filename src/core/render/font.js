export const FONT_CELL = Object.freeze({ width: 6, height: 8 });

export function glyphColumns(character) {
  return GLYPHS[character] || GLYPHS[character.toUpperCase()] || [0x7f, 0x41, 0x41, 0x41, 0x7f];
}

export function wrapText(text, maxChars) {
  const words = String(text || '').split(/\s+/u).filter(Boolean);
  if (!words.length) return [];
  const lines = [];
  let current = words[0];
  for (const word of words.slice(1)) {
    if (`${current} ${word}`.length <= maxChars) current = `${current} ${word}`;
    else {
      lines.push(current);
      current = word;
    }
  }
  lines.push(current);
  return lines;
}
