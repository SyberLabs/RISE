#!/usr/bin/env node
/**
 * Pin the on-device Kev weights.
 *
 * Resolves a ref of the ai-ecoverse/kev.js bundle repository (`main` unless
 * `--ref` names another) to its commit, downloads every file each device
 * model's variant loads at that commit, and writes the commit and each file's
 * size and SHA-256 to src/enterprise/kev-pins.js, which device-model.js
 * reads. Needs the network and, for Kev-4B, about 5 GB of transfer; nothing
 * is kept on disk but the digests. Run it once to pin, and again only to
 * move the pin. Then run the enterprise tests, which check the record's shape.
 *
 *   node scripts/pin-kev-weights.mjs [--ref main] [kev-4b kev-0.8b ...]
 */

import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DEVICE_MODELS, runMatches } from '../src/enterprise/device-model.js';
import KEV_PINS from '../src/enterprise/kev-pins.js';
import { variantFiles } from '../src/enterprise/kev-store.js';

const HUB = 'https://huggingface.co';
const REPO = 'ai-ecoverse/kev.js';
const OUT = new URL('../src/enterprise/kev-pins.js', import.meta.url);

async function fetchOk(url) {
    const response = await fetch(url);
    if (!response.ok || !response.body) throw new Error(`${url}: ${response.status}`);
    return response;
}

/** Download one file, keeping only its size and digest. */
async function measured(url, onBytes) {
    const hash = createHash('sha256');
    let bytes = 0;
    for await (const chunk of (await fetchOk(url)).body) {
        hash.update(chunk);
        bytes += chunk.length;
        onBytes?.(bytes);
    }
    return { bytes, sha256: hash.digest('hex') };
}

/** The pin record for `ids` at `ref`, merged over `pins`. */
export async function pinBundles({ hub = HUB, ref = 'main', ids = Object.keys(DEVICE_MODELS), models = DEVICE_MODELS, pins = KEV_PINS, log = () => {} } = {}) {
    const { sha } = await (await fetchOk(`${hub}/api/models/${REPO}/revision/${encodeURIComponent(ref)}`)).json();
    if (!/^[0-9a-f]{40}$/u.test(sha ?? '')) throw new Error(`${REPO}@${ref} did not resolve to a commit`);
    log(`${REPO}@${ref} is ${sha}`);
    const out = { ...pins };
    for (const id of ids) {
        const model = models[id];
        if (!model) throw new Error(`unknown device model ${id}; have ${Object.keys(models).join(', ')}`);
        const base = `${hub}/${REPO}/resolve/${sha}/${model.bundle}`;
        const manifestBytes = Buffer.from(await (await fetchOk(`${base}/manifest.json`)).arrayBuffer());
        const manifest = JSON.parse(manifestBytes.toString('utf8'));
        if (!runMatches(manifest.run, model.run)) throw new Error(`${model.bundle}@${sha} reports ${manifest.run}, not the pinned ${model.run}`);
        const files = { 'manifest.json': { bytes: manifestBytes.length, sha256: createHash('sha256').update(manifestBytes).digest('hex') } };
        for (const path of variantFiles(manifest, model.variant)) {
            files[path] = await measured(`${base}/${path}`, (bytes) => log(`\r${id}: ${path} ${bytes}`, false));
            log(`\r${id}: ${path} ${files[path].bytes} ${files[path].sha256}`);
        }
        out[id] = { revision: sha, files };
    }
    return out;
}

/** The module text device-model.js imports. */
export function render(pins) {
    return `// Generated by scripts/pin-kev-weights.mjs. Do not edit: run the script.
//
// For each device model: the ai-ecoverse/kev.js commit its bundle is fetched
// from, and the size and SHA-256 of every file the variant loads, the
// manifest first. A model missing here is refused before any fetch.
export default Object.freeze(${JSON.stringify(pins, null, 4)});
`;
}

async function main(argv) {
    let ref = 'main';
    const ids = [];
    for (let i = 0; i < argv.length; i++) {
        if (argv[i] === '--ref') ref = argv[++i];
        else ids.push(argv[i]);
    }
    const log = (line, newline = true) => process.stderr.write(newline ? `${line}\n` : line);
    const pins = await pinBundles({ ref, ...(ids.length ? { ids } : {}), log });
    writeFileSync(OUT, render(pins));
    log(`wrote ${fileURLToPath(OUT)}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    main(process.argv.slice(2)).catch((error) => {
        process.stderr.write(`${error.detail ? `${error.message} (${error.detail})` : error.message}\n`);
        process.exit(1);
    });
}
